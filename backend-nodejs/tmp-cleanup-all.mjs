import dotenv from 'dotenv'; import dns from 'dns'; import mongoose from 'mongoose';
import User from './app/models/User.js'; import Order from './app/models/Order.js'; import Product from './app/models/Product.js';
dotenv.config(); if (process.env.DNS_SERVERS) dns.setServers(process.env.DNS_SERVERS.split(',').map(s => s.trim()));
await mongoose.connect(process.env.MONGODB_URI, { dbName: process.env.MONGODB_DB_NAME || 'supermarket-checkout' });
const users = await User.find({ phoneNumber: /^\+1555555040/ }).select('_id').lean();
const orders = await Order.deleteMany({ $or: [{ userName: /^TEST/, userId: { $in: [...users.map(u => u._id), ...users.map(u => String(u._id))] } }, { userId: /^demo-/ }] });
const products = await Product.deleteMany({ barcode: /^99900000/ });
const removed = await User.deleteMany({ phoneNumber: /^\+1555555040/ });
console.log('cleanup: ' + removed.deletedCount + ' users, ' + orders.deletedCount + ' orders, ' + products.deletedCount + ' products; admins in database: ' + await User.countDocuments({ role: 'admin' }));
await mongoose.disconnect();
